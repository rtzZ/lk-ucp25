async def ensure_description_column(engine) -> None:
    """Колонка subjects.description для БД, созданных до неё.

    create_all колонки не добавляет, Alembic отключён — делаем ALTER вручную,
    только если колонки ещё нет (SQLite PRAGMA / Postgres information_schema).
    """
    from sqlalchemy import text

    dialect = engine.url.get_backend_name()
    async with engine.begin() as conn:
        if dialect == "sqlite":
            cols = await conn.run_sync(
                lambda c: [r[1] for r in c.exec_driver_sql(
                    "PRAGMA table_info(subjects)").fetchall()])
            has = "description" in cols
        else:
            has = (await conn.execute(text(
                "SELECT 1 FROM information_schema.columns "
                "WHERE table_name='subjects' AND column_name='description'"))
            ).first() is not None
        if not has:
            await conn.execute(text(
                "ALTER TABLE subjects ADD COLUMN description TEXT DEFAULT ''"))


async def fill_subject_descriptions(session) -> int:
    """Проставляет описания из макета предметам с пустым description.

    Существующие (в т.ч. ручные правки) не трогает. Возвращает число обновлений.
    """
    from sqlalchemy import select

    from .models import Subject

    rows = (await session.execute(
        select(Subject).where(
            (Subject.description.is_(None)) | (Subject.description == "")))).scalars()
    n = 0
    for subj in rows:
        payload = to_json(subj.name)
        if payload:
            subj.description = payload
            n += 1
    if n:
        await session.commit()
    return n
