def norm_key(name: str) -> str:
    """Канонический ключ: нижний регистр, ё→е, без «(по выбору)», пробелы схлопнуты."""
    t = " ".join(str(name or "").split()).lower().replace("ё", "е")
    t = re.sub(r"\s*\(\s*дисциплина по выбору\s*\)", "", t)
    t = re.sub(r"\s*\(\s*по выбору\s*\)", "", t)
    t = re.sub(r"\s+по выбору\s*$", "", t)
    return t.rstrip(" *").strip()


